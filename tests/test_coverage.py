"""test_coverage.py -- beboputer_tk.tools.coverage (Code Coverage utility).

Covers the .lst listing parser, the address->line map, and
CoverageSession's recording/reporting/attach-detach behaviour, plus a
regression check against a real shipped listing (Data/2funcal.lst) so
the row regex stays honest about the assembler's actual output format.
"""

import os

import pytest

from beboputer_v7.cpu import CPU
from beboputer_tk.tools.coverage import CoverageSession, LineCoverageMap, parse_listing
from compiler_core import Compiler

PROJECT_ROOT = os.path.normpath(os.path.join(os.path.dirname(__file__), '..'))

# A small program with one branch that is always taken (JZ, since ACC==5
# after CMPA $05 sets the Z flag) and one that is therefore never
# executed -- gives a deterministic covered/uncovered split to assert on.
BRANCHY_SRC = """.ORG $4000
        LDA    $05
        CMPA   $05
        JZ     [TAKEN]
        LDA    $FF
        HALT
TAKEN:  LDA    $01
        HALT
"""


def _run_to_halt(cpu, max_steps=1000):
    for _ in range(max_steps):
        if cpu.halted:
            break
        cpu.step()


def _load(cpu, compiled):
    cpu.reset()
    for i, b in enumerate(compiled.bytecode):
        cpu.ram[(compiled.origin + i) & 0xFFFF] = b
    cpu.pc = compiled.origin
    cpu.ram[0xF011] = 0xFF


# ---------------------------------------------------------------------------
# parse_listing / LineCoverageMap
# ---------------------------------------------------------------------------

def test_parse_listing_against_real_reference_file():
    """Data/2funcal.lst is a real, checked-in listing (not generated by
    this test) -- parsing it should find exactly the code/data lines
    it's known to contain, without mistaking any comment/header row for
    one (see coverage.py's _ROW_RE docstring for why that's the tricky
    part)."""
    lst_path = os.path.join(PROJECT_ROOT, 'Data', '2funcal.lst')
    with open(lst_path, encoding='latin-1') as fh:
        text = fh.read()

    rows = parse_listing(text)
    coded = [r for r in rows if r.addr is not None]
    assert coded, "expected at least one addressed row"

    # Line 25 is `4000 90 10     INIT:     LDA    CLRCODE` per the file.
    by_line = {r.line_no: r.addr for r in coded}
    assert by_line[25] == 0x4000

    # No comment/header/xref row (e.g. line 1 "#####...", or the blank
    # line 17) should have been mistaken for a coded line.
    assert 1 not in by_line
    assert 17 not in by_line


def test_line_coverage_map_bisects_multibyte_instructions():
    listing_text = Compiler().generate_listing(BRANCHY_SRC).text
    m = LineCoverageMap(parse_listing(listing_text))

    assert m.executable_lines == {2, 3, 4, 5, 6, 7, 8}
    assert m.address_for_line(2) == 0x4000
    assert m.address_for_line(4) == 0x4004    # JZ [TAKEN]

    # JZ is a 3-byte instruction ($D1 + 2-byte address) starting at
    # $4004 -- the operand bytes ($4005/$4006) belong to line 4 too,
    # even though only $4004 itself is a real "line start".
    assert m.line_for_address(0x4004) == 4
    assert m.line_for_address(0x4005) == 4
    assert m.line_for_address(0x4006) == 4
    assert m.line_for_address(0x4007) == 5     # next line's LDA $FF

    # An address before the program's own origin has no owning line.
    assert m.line_for_address(0x0000) is None


