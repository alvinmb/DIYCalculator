def test_coverage_session_from_source_reports_untaken_branch():
    session = CoverageSession.from_source(BRANCHY_SRC, source_path="branchy.asm")

    compiled = Compiler().compile_source(BRANCHY_SRC)
    cpu = CPU()
    _load(cpu, compiled)

    executed = session.run_headless(cpu, max_steps=1000)
    assert executed > 0
    assert cpu.halted

    rep = session.report()
    assert rep.total_executable == 7
    assert rep.covered == {2, 3, 4, 7, 8}
    assert rep.uncovered == {5, 6}
    assert rep.percent == pytest.approx(5 / 7 * 100)
    assert not rep.unmapped_addresses

    text = session.render_text_report(title="Branchy")
    assert "Coverage" in text
    assert "LDA    $FF" in text          # the uncovered line's source, quoted back

    annotated = session.render_annotated_source()
    lines = annotated.splitlines()
    assert lines[1].startswith("+")       # line 2, covered
    assert lines[4].startswith("!")       # line 5, uncovered
    assert lines[0].startswith(" ")       # line 1 (.ORG), not executable


def test_coverage_accumulates_across_multiple_runs_until_reset():
    """Matches the tool's actual use case: run a program more than once
    (different inputs/paths taken) and coverage should accumulate, not
    reset itself, until the caller explicitly asks it to."""
    session = CoverageSession.from_source(BRANCHY_SRC)
    compiled = Compiler().compile_source(BRANCHY_SRC)

    # First run: force the untaken branch by starting execution straight
    # from the "LDA $FF" line instead of the top, covering lines 5-6
    # without ever touching 2-4/7-8.
    cpu = CPU()
    _load(cpu, compiled)
    cpu.pc = compiled.origin + 7     # address of the "LDA $FF" line ($4007)
    session.run_headless(cpu, max_steps=1000)
    rep1 = session.report()
    assert rep1.covered == {5, 6}

    # Second run: the normal path (JZ taken) -- coverage should ADD to
    # the first run's hits, not replace them.
    cpu2 = CPU()
    _load(cpu2, compiled)
    session.run_headless(cpu2, max_steps=1000)
    rep2 = session.report()
    assert rep2.covered == {2, 3, 4, 5, 6, 7, 8}   # union of both runs
    assert rep2.uncovered == set()

    session.reset()
    rep3 = session.report()
    assert rep3.covered == set()
    assert len(rep3.uncovered) == rep3.total_executable == 7


def test_attach_wraps_and_detach_restores_cpu_step():
    session = CoverageSession.from_source(BRANCHY_SRC)
    compiled = Compiler().compile_source(BRANCHY_SRC)
    cpu = CPU()
    _load(cpu, compiled)

    original_step = cpu.step
    session.attach(cpu)
    assert session.attached
    assert cpu.step is not original_step

    _run_to_halt(cpu)
    rep = session.report()
    assert rep.covered == {2, 3, 4, 7, 8}

    session.detach()
    assert not session.attached
    # Bound methods aren't interned -- `is` would fail even when detach()
    # correctly restored the original method, since re-accessing cpu.step
    # mints a fresh bound-method wrapper each time. `==` compares
    # __self__/__func__, which is what actually matters here.
    assert cpu.step == original_step

    # Stepping after detach must NOT add further hits.
    cpu2 = CPU()
    _load(cpu2, compiled)
    cpu2.step()   # not tracked -- session was detached before this ran
    rep_after = session.report()
    assert rep_after.covered == {2, 3, 4, 7, 8}   # unchanged


def test_render_annotated_source_requires_source_lines():
    listing_text = Compiler().generate_listing(BRANCHY_SRC).text
    session = CoverageSession(listing_text)   # no source_lines passed
    with pytest.raises(RuntimeError):
        session.render_annotated_source()


def test_from_source_raises_on_bad_assembly():
    with pytest.raises(RuntimeError):
        CoverageSession.from_source(".ORG $4000\n        NOTAREALMNEMONIC\n")
